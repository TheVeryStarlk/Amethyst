using System.Collections.Immutable;
using System.Text;

namespace Amethyst.Generators;

internal static class Source
{
    private const string Variable = "global::Amethyst.Networking.Variable";

    public static string WriteCreators(ImmutableArray<string> packets)
    {
        var builder = new StringBuilder();

        foreach (var packet in packets.OrderBy(packet => packet, StringComparer.Ordinal))
        {
            builder.Append($"            {{ ({packet}.State, {packet}.Identifier), static packet => packet.Create<{packet}>() }},\n");
        }

        return $$"""
                 // <auto-generated/>
                 #nullable enable

                 namespace Amethyst.Networking.Packets;

                 internal static partial class PacketExtensions
                 {
                     private static partial global::System.Collections.Generic.Dictionary<(global::Amethyst.State State, int Identifier), global::System.Func<global::Amethyst.Networking.Packets.Packet, global::Amethyst.Networking.Packets.IProcessor>> Creators()
                     {
                         return new global::System.Collections.Generic.Dictionary<(global::Amethyst.State State, int Identifier), global::System.Func<global::Amethyst.Networking.Packets.Packet, global::Amethyst.Networking.Packets.IProcessor>>
                         {
                 {{builder}}        };
                     }
                 }
                 """;
    }

    public static string WriteSerializers(ImmutableArray<(string Packet, string Serializer)> pairs)
    {
        var builder = new StringBuilder();

        foreach (var (packet, serializer) in pairs.OrderBy(pair => pair.Packet, StringComparer.Ordinal))
        {
            builder.Append($"            {packet} packet => {serializer}.Create(packet),\n");
        }

        return $$"""
                 // <auto-generated/>
                 #nullable enable

                 namespace Amethyst.Networking.Serializers;

                 internal static partial class OutgoingPacketExtensions
                 {
                     public static partial global::Amethyst.Networking.Serializers.ISerializer Create(this global::Amethyst.Abstractions.Packets.IOutgoingPacket instance)
                     {
                         return instance switch
                         {
                 {{builder}}            _ => throw new global::System.ArgumentOutOfRangeException(nameof(instance), instance, "Unknown packet.")
                         };
                     }
                 }
                 """;
    }

    public static string WriteMembers(Target target)
    {
        var members = new List<string>();

        if (target.Members.HasFlag(Members.Create))
        {
            members.Add(WriteCreate(target));
        }

        if (target.Members.HasFlag(Members.Length))
        {
            members.Add(WriteLength(target));
        }

        if (target.Members.HasFlag(Members.Write))
        {
            members.Add(WriteWrite(target));
        }

        var space = target.Namespace is null ? string.Empty : $"namespace {target.Namespace};\n\n";

        return $$"""
                 // <auto-generated/>
                 #nullable enable

                 {{space}}partial class {{target.Name}}
                 {
                 {{string.Join("\n\n", members)}}
                 }
                 """;
    }

    private static string WriteCreate(Target target)
    {
        if (target.Fields.IsEmpty)
        {
            return $$"""
                         public static {{target.Type}} Create(global::System.ReadOnlySpan<byte> span)
                         {
                             return new {{target.Type}}();
                         }
                     """;
        }

        var arguments = new List<string>();

        foreach (var field in target.Fields)
        {
            var read = $"reader.Read{field.Kind}()";
            arguments.Add(field.Cast is null ? read : $"({field.Cast}) {read}");
        }

        return $$"""
                     public static {{target.Type}} Create(global::System.ReadOnlySpan<byte> span)
                     {
                         var reader = new global::Amethyst.Networking.Packets.SpanReader(span);

                         return new {{target.Type}}(
                             {{string.Join(",\n            ", arguments)}});
                     }
                 """;
    }

    private static string WriteLength(Target target)
    {
        IEnumerable<string> lengths = target.Fields.IsEmpty ? ["0"] : target.Fields.Select(GetLength);
        return $"    public int Length => {string.Join(" + ", lengths)};";
    }

    private static string GetLength(Field field)
    {
        if (!field.IsArray)
        {
            return field.Kind is Kind.VariableInteger or Kind.VariableString
                ? $"{Variable}.GetByteCount({GetValue(field, field.Name)})"
                : GetSize(field.Kind);
        }

        var count = $"{Variable}.GetByteCount({field.Name}.Length)";

        return field.Kind is Kind.VariableInteger or Kind.VariableString
            ? $"{count} + global::System.Linq.Enumerable.Sum({field.Name}, {Variable}.GetByteCount)"
            : $"{count} + {field.Name}.Length * {GetSize(field.Kind)}";
    }

    private static string GetSize(Kind kind)
    {
        return kind switch
        {
            Kind.Byte => "sizeof(byte)",
            Kind.Boolean => "sizeof(bool)",
            Kind.Short => "sizeof(short)",
            Kind.UnsignedShort => "sizeof(ushort)",
            Kind.Integer => "sizeof(int)",
            Kind.Long or Kind.Position => "sizeof(long)",
            Kind.Float => "sizeof(float)",
            Kind.Double => "sizeof(double)",
            Kind.Guid => "16",
            _ => throw new ArgumentOutOfRangeException(nameof(kind), kind, "Variable kinds have no fixed size.")
        };
    }

    private static string WriteWrite(Target target)
    {
        var builder = new StringBuilder();

        foreach (var field in target.Fields)
        {
            if (!field.IsArray)
            {
                builder.Append($"\n        writer.Write{field.Kind}({GetValue(field, field.Name)});");
                continue;
            }

            builder.Append($"\n        writer.WriteVariableInteger({field.Name}.Length);");

            // Byte arrays are copied as a whole.
            builder.Append(field.Kind is Kind.Byte
                ? $"\n        writer.Write({field.Name});"
                : $"\n\n        foreach (var element in {field.Name})\n        {{\n            writer.Write{field.Kind}(element);\n        }}");
        }

        var body = target.Fields.IsEmpty
            ? string.Empty
            : $"        var writer = global::Amethyst.Networking.SpanWriter.Create(span);\n{builder}";

        return $$"""
                     public void Write(global::System.Span<byte> span)
                     {
                 {{body}}
                     }
                 """;
    }

    private static string GetValue(Field field, string value)
    {
        if (field.Cast is null)
        {
            return value;
        }

        return field.Kind is Kind.VariableInteger ? $"(int) {value}" : $"(byte) {value}";
    }
}